(function (root) {
  'use strict';

  function rgb565(r, g, b) {
    return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
  }

  // Run-length encoding of one indexed frame, row-major: pairs of (count 1..255, palette index).
  function encodeFrame(index) {
    const out = [];
    let i = 0;
    while (i < index.length) {
      const c = index[i];
      let n = 1;
      while (n < 255 && i + n < index.length && index[i + n] === c) n++;
      out.push(n, c);
      i += n;
    }
    return out;
  }

  function decodeFrame(bytes, start, end, length) {
    const out = new Uint8Array(length);
    let p = start, o = 0;
    while (p < end) { out.fill(bytes[p + 1], o, o + bytes[p]); o += bytes[p]; p += 2; }
    return out;
  }

  function cName(text) {
    const s = String(text || 'crystal').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
    return /^[a-z_]/.test(s) ? s : 'anim_' + s;
  }

  function hexRows(values, perRow, fmt) {
    const rows = [];
    for (let i = 0; i < values.length; i += perRow) rows.push('  ' + Array.from(values.slice(i, i + perRow), fmt).join(', '));
    return rows.join(',\n');
  }

  // frames: array of Uint8Array palette indexes (width * height each); palette: [[r, g, b], ...] (<= 256 entries).
  function buildHeader({ title, width, height, fps, loop, palette, frames }) {
    if (palette.length > 256) throw new RangeError('256 couleurs au maximum.');
    const data = [], offsets = [0];
    for (const f of frames) {
      if (f.length !== width * height) throw new RangeError('Image de taille incorrecte.');
      for (const b of encodeFrame(f)) data.push(b);
      offsets.push(data.length);
    }
    const P = 'CRYSTAL_BOOT', p = 'crystal_boot';
    const pal = palette.map(([r, g, b]) => rgb565(r, g, b));
    const bytes = data.length + offsets.length * 4 + pal.length * 2;
    const text = [
      '// Generated by Crystal Boot: https://github.com/nktrois/crystal-boot',
      `// "${String(title || '').replace(/[^\x20-\x7e]/g, '?')}" · ${width}x${height} · ${frames.length} frames · ${fps} fps · ${pal.length} colors · ${bytes} bytes`,
      '// Format: RGB565 palette, then each frame as (count, palette index) byte pairs, row by row.',
      '#pragma once',
      '#include <stdint.h>',
      '#ifndef PROGMEM',
      '#define PROGMEM',
      '#endif',
      '',
      `#define ${P}_WIDTH ${width}`,
      `#define ${P}_HEIGHT ${height}`,
      `#define ${P}_FRAMES ${frames.length}`,
      `#define ${P}_FPS ${fps}`,
      `#define ${P}_LOOP ${loop ? 1 : 0}`,
      `#define ${P}_COLORS ${pal.length}`,
      '',
      `static const uint16_t ${p}_palette[${pal.length}] PROGMEM = {`,
      hexRows(pal, 12, v => '0x' + v.toString(16).padStart(4, '0')),
      '};',
      '',
      `static const uint32_t ${p}_offsets[${offsets.length}] PROGMEM = {`,
      hexRows(offsets, 10, v => String(v)),
      '};',
      '',
      `static const uint8_t ${p}_data[${data.length}] PROGMEM = {`,
      hexRows(data, 20, v => '0x' + v.toString(16).padStart(2, '0')),
      '};',
      ''
    ].join('\n');
    return { text, bytes, name: cName(title) };
  }

  const api = { rgb565, encodeFrame, decodeFrame, buildHeader, cName };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.CrystalExport = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
